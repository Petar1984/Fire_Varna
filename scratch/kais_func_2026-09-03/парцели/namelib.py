# Street / locality names that produce look-alike hits and are NOT institutions.
STREET_NOISE = re.compile(
    'академик|здравец|здравко|ботаническа градина|морска градина|'
    'морската градина|капелова градина|райска градина|зимна градина',
    re.IGNORECASE)


def scan_name(addr):
    """(hits, noisy) — institutional tokens found in a KAIS addr string."""
    hits = []
    for m in RE_ABBR.finditer(addr):
        t = m.group(1)
        hits.append((t, CLASS_OF_ABBR.get(t, '?')))
    for m in RE_STEM.finditer(addr):
        t = re.sub(r'\s+', ' ', m.group(1).lower())
        hits.append((t, CLASS_OF_STEM.get(t, '?')))
    seen, out = set(), []
    for h in hits:
        if h not in seen:
            seen.add(h)
            out.append(h)
    noisy = bool(STREET_NOISE.search(addr))
    return out, noisy


# ---------------------------------------------------------------- addresses
_PUNCT_CHARS = '"' + "'" + '`.,-()[]/' + '„“”–—№#' + chr(92) + '«»‘’'
_PUNCT = re.compile('[' + re.escape(_PUNCT_CHARS) + ']+')
_WS = re.compile(r'\s+')

# Ordinal numerals in street names ("ул. 6-ти септември" == "ул. Шести септември").
ORD_M = {1: 'първи', 2: 'втори', 3: 'трети', 4: 'четвърти', 5: 'пети',
         6: 'шести', 7: 'седми', 8: 'осми', 9: 'девети', 10: 'десети',
         11: 'единадесети', 12: 'дванадесети', 13: 'тринадесети',
         14: 'четиринадесети', 15: 'петнадесети', 16: 'шестнадесети',
         17: 'седемнадесети', 18: 'осемнадесети', 19: 'деветнадесети',
         20: 'двадесети'}
ORD_F = {n: (w[:-1] + 'а') for n, w in ORD_M.items()}
_ORD_RE = re.compile('(?<![0-9])([0-9]{1,2})[ ]+(ви|ри|ти|ми|ма|ра|та|во|ро|то)(?![а-я])')


def ordinal_variants(s):
    """[s] plus the masculine / feminine spelled-out variants of "6 ти" etc."""
    out = [s]
    for table in (ORD_M, ORD_F):
        t = _ORD_RE.sub(lambda m: table.get(int(m.group(1)), m.group(0)), s)
        if t != s and t not in out:
            out.append(t)
    return out


def norm_addr(s):
    s = s.lower()
    s = s.replace('ё', 'е')
    s = _PUNCT.sub(' ', s)
    s = _WS.sub(' ', s).strip()
    s = re.sub(r'^(гр\s+)?варна\s+', '', s)
    s = re.sub(r'^гр\s+', '', s)
    s = re.sub(r'\bгр\s+варна\b', ' ', s)
    s = re.sub(r'\bр\s+н\b|\bрайон\b', ' ', s)
    s = re.sub(r'\bж\s+к\b', 'жк', s)
    s = re.sub(r'\bк\s+к\b', 'кк', s)
    s = re.sub(r'\bм\s+р\b', 'мр', s)
    s = _WS.sub(' ', s).strip()
    return s
